const catalogs: Readonly<Record<string, XlsxViewerMessages>> = {
  en: englishMessages, fr: frMessages, de: deMessages, es: esMessages,
  ja: jaMessages, pt: ptMessages, it: itMessages, zh: zhMessages
};

export function resolveMessages(locale = "en-US", overrides?: Partial<XlsxViewerMessages>): XlsxViewerMessages {
  let language = "en";
  try {
    language = new Intl.Locale(locale).language;
  } catch {
    // Invalid language tags use the default message catalog.
  }
  return mergeMessages({ ...(catalogs[language] ?? englishMessages) }, overrides);
}

export function mergeMessages(defaults: XlsxViewerMessages, overrides?: Partial<XlsxViewerMessages>): XlsxViewerMessages {
  if (!overrides) return defaults;
  const messages = { ...defaults };
  for (const key of Object.keys(englishMessages) as Array<keyof XlsxViewerMessages>) {
    if (overrides[key] !== undefined) messages[key] = overrides[key];
  }
  return messages;
}

export function formatMessage(message: string, values: Record<string, string>): string {
  return message.replace(/\{(\w+)\}/g, (placeholder, key: string) => values[key] ?? placeholder);
}
